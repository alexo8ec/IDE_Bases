    public static Set<String> base() { return BASE; }
    private static Set<String> words(String source) {
        return Collections.unmodifiableSet(new LinkedHashSet<>(Arrays.asList(source.trim().split("\\s+"))));
    }
    public static Set<String> forDatabase(DatabaseMetaData metadata) {
        Set<String> result=new LinkedHashSet<>(BASE);
        // Some drivers implement only part of this metadata. Keep the complete fallback on failure.
        for(int i=0;i<5;i++)try {
            String extra=switch(i){case 0->metadata.getSQLKeywords();case 1->metadata.getNumericFunctions();
                case 2->metadata.getStringFunctions();case 3->metadata.getSystemFunctions();default->metadata.getTimeDateFunctions();};
            if(extra!=null)for(String word:extra.split(","))if(word.trim().matches("[A-Za-z_][A-Za-z_0-9]*"))result.add(word.trim().toUpperCase(Locale.ROOT));
        }catch(SQLException|AbstractMethodError ignored){}
        try {
            String product=metadata.getDatabaseProductName().toLowerCase(Locale.ROOT);
            if(product.contains("mysql")||product.contains("mariadb"))try(var statement=metadata.getConnection().createStatement()){
                try{statement.setQueryTimeout(3);}catch(SQLException ignored){}
                try(var rows=statement.executeQuery("SELECT WORD FROM INFORMATION_SCHEMA.KEYWORDS")){
                    while(rows.next()){String word=rows.getString(1);if(word!=null&&word.matches("[A-Za-z_][A-Za-z_0-9]*"))result.add(word.toUpperCase(Locale.ROOT));}
                }
            }
        }catch(SQLException|AbstractMethodError ignored){} // Older server versions still use JDBC + built-ins.
        return Collections.unmodifiableSet(result);
    }
