package com.nexodb.db;

import com.nexodb.model.DatabaseType;
import java.nio.file.Files;
import java.sql.DriverManager;

public final class PortableBackupServiceTest {
    public static void main(String[] args)throws Exception{
        var file=Files.createTempFile("adisdb-portable-",".sql");
        try(var source=DriverManager.getConnection("jdbc:h2:mem:portable_source;DB_CLOSE_DELAY=-1")){
            source.createStatement().execute("CREATE TABLE PRODUCTOS(ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,NOMBRE VARCHAR(80) NOT NULL,PRECIO DECIMAL(10,2),ACTIVO BOOLEAN,IMAGEN VARBINARY(16))");
            source.createStatement().execute("INSERT INTO PRODUCTOS(NOMBRE,PRECIO,ACTIVO,IMAGEN) VALUES ('Café niño',12.50,TRUE,X'0A0B')");
            var objects=PortableBackupService.objects(source,"portable_source");
            var report=PortableBackupService.write(source,DatabaseType.H2,"portable_source",objects,new SqlBackupService.Options(SqlBackupService.Mode.STRUCTURE_AND_DATA,false,true,true,true,true),file,new SqlTransferControl(),progress->{});
            equal(1L,report.rows());
        }
        String sql=Files.readString(file);contains(sql,"DROP TABLE IF EXISTS");contains(sql,"CREATE TABLE");contains(sql,"Café niño");contains(sql,"X'0a0b'");
        try(var target=DriverManager.getConnection("jdbc:h2:mem:portable_target;DB_CLOSE_DELAY=-1")){
            var analysis=SqlImportService.analyze(file,new SqlTransferControl());
            PortableBackupService.restore(target,DatabaseType.H2,analysis,new SqlTransferControl(),progress->{});
            try(var rows=target.createStatement().executeQuery("SELECT NOMBRE,PRECIO,ACTIVO FROM PRODUCTOS")){equal(true,rows.next());equal("Café niño",rows.getString(1));equal("12.50",rows.getBigDecimal(2).toPlainString());equal(true,rows.getBoolean(3));equal(false,rows.next());}
        }finally{Files.deleteIfExists(file);}
        System.out.println("PortableBackupServiceTest: OK (streamed structure, data, binary and restore)");
    }
    private static void contains(String value,String expected){if(!value.contains(expected))throw new AssertionError("Missing "+expected+" in\n"+value);}
    private static void equal(Object expected,Object actual){if(!java.util.Objects.equals(expected,actual))throw new AssertionError("Expected "+expected+" got "+actual);}
}
